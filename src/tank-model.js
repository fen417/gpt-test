// Authored mesh parts and the shared pivots used by the game simulation.
const wheelAxis=new THREE.Vector3(1,0,0),position=new THREE.Vector3(),scale=new THREE.Vector3(),quaternion=new THREE.Quaternion(),matrix=new THREE.Matrix4();
const modelDirection={x:0,y:0,z:0};
const barrelVertex=new THREE.Vector3();
const desertSand={value:new THREE.Color(0xe0c897)},desertBrown={value:new THREE.Color(0xa8875e)};
let atlas,atlasPromise,modelPromise,detailPromise,detailAssets;
const modelParts=new Map();
const tankParts=['hull','turret','cannon','hatch','belt','wheel'];
const trackSegments=[];
let trackLength=0;
for(let i=0;i<trackPath.points.length;i++){
  const [z,y]=trackPath.points[i], [nextZ,nextY]=trackPath.points[(i+1)%trackPath.points.length];
  const dz=nextZ-z,dy=nextY-y,length=Math.hypot(dz,dy);
  trackSegments.push({z,y,dz,dy,length,start:trackLength,angle:Math.atan2(dy,-dz)});
  trackLength+=length;
}

// The tank atlas is originally generated by scripts/bake-tank.mjs. Rebuild
// exactly the same 512x512 artwork as a regular CanvasTexture on WebGPU:
// KTX2Loader may choose a compressed format that the requested GPUDevice
// does not enable (we intentionally request no optional compression features).
// WebGL continues to use the original compressed KTX2 texture.
function makeWebGpuTankAtlas() {
  const canvas=document.createElement('canvas');
  canvas.width=canvas.height=512;
  const ctx=canvas.getContext('2d');
  if(!ctx)throw new Error('Не удалось создать Canvas 2D для атласа танка.');
  ctx.fillStyle='#c8cbbb';
  ctx.fillRect(0,0,512,512);
  let seed=417;
  const random=()=>((seed=(Math.imul(seed,1664525)+1013904223)>>>0)/4294967296);
  for(let i=0;i<180;i++){
    ctx.fillStyle=['#a6ae96','#b2b99f','#d6d8c9'][i%3];
    ctx.beginPath();
    const x=random()*512,y=random()*512;
    ctx.moveTo(x,y);
    for(let j=0;j<6;j++)ctx.lineTo(
      x+Math.cos(j*Math.PI/3)*(12+random()*40),
      y+Math.sin(j*Math.PI/3)*(10+random()*30)
    );
    ctx.closePath();
    ctx.fill();
  }
  const texture=new THREE.CanvasTexture(canvas);
  texture.flipY=false;
  return texture;
}

export function loadTankAtlas(renderer) {
  if(atlasPromise)return atlasPromise;
  const webgpu=renderer.isWebGPURenderer===true;
  atlasPromise=(async()=>{
    let texture;
    if(webgpu){
      texture=makeWebGpuTankAtlas();
    }else{
      texture=await loadCompressedTexture(renderer,new URL('./assets/tank/atlas.ktx2',import.meta.url).href);
    }
    texture.colorSpace=THREE.SRGBColorSpace;
    texture.wrapS=texture.wrapT=THREE.RepeatWrapping;
    texture.anisotropy=Math.min(16,renderer.capabilities?.getMaxAnisotropy?.()??renderer.getMaxAnisotropy?.()??1);
    atlas=texture;
    return texture;
  })().catch(error=>{atlasPromise=null;throw error;});
  return atlasPromise;
}
function tankGeometry(mesh,detailed=false){
  const geometry=mesh.geometry;
  const {position,color,uv,uv1,normal}=geometry.attributes;
  if(!position||!normal||!uv||!color||(detailed&&(!uv1||color.itemSize!==4))){
    throw Error('Invalid Rubezh mesh: '+mesh.name);
  }
  if(color.itemSize===4){
    const rgb=new Float32Array(color.count*3),paint=detailed?new Float32Array(color.count):null;
    for(let i=0;i<color.count;i++){
      rgb[i*3]=color.getX(i);rgb[i*3+1]=color.getY(i);rgb[i*3+2]=color.getZ(i);
      if(paint)paint[i]=color.getW(i);
    }
    geometry.setAttribute('color',new THREE.BufferAttribute(rgb,3));
    if(paint)geometry.setAttribute('tankPaint',new THREE.BufferAttribute(paint,1));
  }
  if(!detailed){
    const trackSide=new Float32Array(position.count);
    if(mesh.name.endsWith('_belt')){
      for(let i=0;i<position.count;i++)trackSide[i]=Math.sign(position.getX(i));
    }
    geometry.setAttribute('trackSide',new THREE.BufferAttribute(trackSide,1));
  }
  geometry.userData.sharedTankGeometry=true;
  return geometry;
}

export function loadTankModel(){
  return modelPromise??=new GLTFLoader().setMeshoptDecoder(MeshoptDecoder)
    .loadAsync(new URL('./assets/tank/rubezh.glb',import.meta.url).href)
    .then(({scene})=>{
      scene.traverse(mesh=>{
        if(!mesh.isMesh)return;
        const part=mesh.name.slice(mesh.name.indexOf('_')+1);
        if(tankParts.includes(part))modelParts.set(mesh.name,tankGeometry(mesh));
        else mesh.geometry.dispose();
        mesh.material.dispose();
      });
      for(let level=0;level<3;level++){
        for(const part of tankParts){
          if(!modelParts.has('LOD'+level+'_'+part))throw Error('Missing Rubezh mesh: '+part);
        }
      }
    })
    .catch(error=>{
      for(const geometry of modelParts.values())geometry.dispose();
      modelParts.clear();modelPromise=null;throw error;
    });
}

function loadTankDetail(){
  return detailPromise??=new GLTFLoader().setMeshoptDecoder(MeshoptDecoder)
    .loadAsync(new URL('./assets/tank/rubezh-high.glb',import.meta.url).href)
    .then(({scene})=>{
      const parts=new Map();
      const surface=scene.getObjectByName('HD_hull')?.material;
      try{
        for(const part of [...tankParts,'shoe']){
          const mesh=scene.getObjectByName('HD_'+part);
          if(!mesh?.isMesh||mesh.material!==surface)throw Error('Missing detailed Rubezh part: '+part);
          parts.set(mesh.name,tankGeometry(mesh,true));
        }
        if(!surface.map||!surface.normalMap||!surface.roughnessMap||!surface.metalnessMap)throw Error('Missing Rubezh PBR maps');
      }catch(error){
        scene.traverse(mesh=>{if(mesh.isMesh)mesh.geometry.dispose();});
        for(const value of Object.values(surface??{}))if(value?.isTexture)value.dispose();
        surface?.dispose();
        throw error;
      }
      detailAssets={parts,surface};
    }).catch(error=>console.warn('Detailed Rubezh:',error));
}

function batchDistantTank(hull,hatch,tracks,turretMesh,barrel,gun){
  const hullParts=[hull.geometry,hatch.geometry,tracks.geometry];
  hull.geometry=mergeGeometries(hullParts,false);
  for(const geometry of hullParts)geometry.dispose();
  hatch.removeFromParent();
  tracks.removeFromParent();

  // Keep two draws: hull with scrolling tracks, and the rotating turret.
  // The barrel shares the turret mesh, with only its vertices posed on demand.
  const turretGeometry=turretMesh.geometry,barrelGeometry=barrel.geometry;
  const offset=turretGeometry.attributes.position.count;
  const restPosition=barrelGeometry.attributes.position,restNormal=barrelGeometry.attributes.normal;
  turretMesh.geometry=mergeGeometries([turretGeometry,barrelGeometry],false);
  const {position:vertices,normal:normals}=turretMesh.geometry.attributes;
  vertices.setUsage(THREE.DynamicDrawUsage);
  normals.setUsage(THREE.DynamicDrawUsage);
  turretGeometry.dispose();
  barrelGeometry.dispose();
  barrel.removeFromParent();

  let lastPitch,lastRecoil;
  const updateBarrel=()=>{
    if(gun.rotation.x===lastPitch&&gun.position.z===lastRecoil)return;
    lastPitch=gun.rotation.x;
    lastRecoil=gun.position.z;
    gun.updateMatrix();
    for(let i=0;i<restPosition.count;i++){
      barrelVertex.fromBufferAttribute(restPosition,i).applyMatrix4(gun.matrix);
      vertices.setXYZ(offset+i,barrelVertex.x,barrelVertex.y,barrelVertex.z);
      barrelVertex.fromBufferAttribute(restNormal,i).transformDirection(gun.matrix);
      normals.setXYZ(offset+i,barrelVertex.x,barrelVertex.y,barrelVertex.z);
    }
    for(const attribute of [vertices,normals]){
      attribute.clearUpdateRanges();
      attribute.addUpdateRange(offset*3,restPosition.count*3);
      attribute.needsUpdate=true;
    }
    turretMesh.geometry.computeBoundingSphere();
  };
  updateBarrel();
  return updateBarrel;
}
function buildLevel(level,material,parts=modelParts){
  const detailed=level==='HD';
  const prefix=detailed?'HD':'LOD'+level;
  const group=new THREE.Group(),body=new THREE.Group();
  const turret=new THREE.Group(),gun=new THREE.Group();
  group.add(body);
  body.add(turret);
  turret.position.set(0,TANK_TURRET_BASE_Y,-.4);
  turret.add(gun);
  gun.position.set(0,.34,-.9);
  const geometry=name=>parts.get(prefix+'_'+name);
  const attach=(parent,name,mergeAtDistance=false)=>{
    const source=geometry(name);
    // Far LOD poses its barrel inside a merged, per-instance vertex buffer.
    const instanceGeometry=level===2&&mergeAtDistance
      ?(source.index?source.toNonIndexed():source.clone()):source;
    if(instanceGeometry!==source)instanceGeometry.userData.sharedTankGeometry=false;
    const mesh=new THREE.Mesh(instanceGeometry,material);
    parent.add(mesh);
    return mesh;
  };
  const hull=attach(body,'hull',true),hatch=attach(body,'hatch',true),tracks=attach(body,'belt',true);
  const turretMesh=attach(turret,'turret',true),barrel=attach(gun,'cannon',true);
  const wheels=new THREE.InstancedMesh(geometry('wheel'),material,12);
  wheels.instanceMatrix.setUsage(THREE.DynamicDrawUsage);
  for(let i=0;i<wheels.count;i++){
    matrix.makeTranslation(i<6?-1.67:1.67,.414,-2.65+i%6*1.06);
    wheels.setMatrixAt(i,matrix);
  }
  body.add(wheels);
  const updateBarrel=level===2?batchDistantTank(hull,hatch,tracks,turretMesh,barrel,gun):null;
  const updateShoes=detailed?addTrackShoes(body,geometry('shoe'),material):null;
  if(detailed){
    for(const mesh of [hull,turretMesh,barrel,hatch,tracks,wheels]){
      mesh.castShadow=true;
      mesh.receiveShadow=true;
    }
  }
  return {group,body,turret,gun,hull,turretMesh,hatch,tracks,wheels,updateBarrel,updateShoes};
}

function addTrackShoes(body,geometry,material){
  const count=trackPath.links,spacing=trackLength/count;
  const shoes=new THREE.InstancedMesh(geometry,material,count*2);
  shoes.instanceMatrix.setUsage(THREE.DynamicDrawUsage);
  shoes.receiveShadow=true;
  body.add(shoes);
  const lastTravel=new THREE.Vector2(Infinity,Infinity);
  const update=(left,right)=>{
    if(lastTravel.x===left&&lastTravel.y===right)return;
    lastTravel.set(left,right);
    for(let side=0;side<2;side++){
      const x=side===0?-trackPath.x:trackPath.x;
      let distance=THREE.MathUtils.euclideanModulo((side===0?left:right)/.35,trackLength);
      let segment=0;
      for(let i=0;i<count;i++){
        while(segment<trackSegments.length-1&&distance>=trackSegments[segment+1].start)segment++;
        const {y,z,dy,dz,length,start,angle}=trackSegments[segment];
        const t=(distance-start)/length;
        matrix.compose(position.set(x,y+dy*t,z+dz*t),quaternion.setFromAxisAngle(wheelAxis,angle),scale.set(1,1,1));
        shoes.setMatrixAt(side*count+i,matrix);
        distance+=spacing;
        if(distance>=trackLength){distance-=trackLength;segment=0;}
      }
    }
    shoes.instanceMatrix.needsUpdate=true;
  };
  update(0,0);
  shoes.computeBoundingSphere();
  shoes.boundingSphere.radius+=spacing;
  return update;
}

function tankMaterial(materialFactory,travel,desertCamo,detail=null){
  const surface=detail?.surface;
  if(materialFactory)return materialFactory({atlas,travel,desertCamo,desertSand,desertBrown,surface});
  const material=surface?surface.clone():new THREE.MeshLambertMaterial({map:atlas??null});
  material.vertexColors=true;
  if(surface)material.envMapIntensity=.4;
  material.onBeforeCompile=shader=>{
    Object.assign(shader.uniforms,{tankTravel:travel,desertCamo,desertSand,desertBrown});
    if(surface)shader.uniforms.tankCamouflage={value:atlas};
    const attributes=surface?`#ifndef USE_UV1
      attribute vec2 uv1;
      #endif
      attribute float tankPaint;
      varying float vTankPaint;
      varying vec2 vTankCamoUv;`:
      'attribute float trackSide;uniform vec2 tankTravel;';
    const setAttributes=surface?'vTankPaint=tankPaint;vTankCamoUv=uv1;':
      '#ifdef USE_MAP\nif(abs(trackSide)>.5)vMapUv.y+=trackSide<0.?tankTravel.x:tankTravel.y;\n#endif';
    const paint=surface?'vTankPaint':'smoothstep(.08,.17,vColor.r)';
    const camoSample=surface?'texture2D(tankCamouflage,vTankCamoUv).rgb':'sampledDiffuseColor.rgb';
    shader.vertexShader=shader.vertexShader
      .replace('#include <common>','#include <common>\n'+attributes)
      .replace('#include <uv_vertex>','#include <uv_vertex>\n'+setAttributes);
    // Use the existing camouflage shapes and leave the dark hardware unpainted.
    shader.fragmentShader=shader.fragmentShader
      .replace('#include <common>',`#include <common>
        ${surface?'uniform sampler2D tankCamouflage;varying float vTankPaint;varying vec2 vTankCamoUv;':''}
        uniform bool desertCamo;
        uniform vec3 desertSand;
        uniform vec3 desertBrown;`)
      .replace('#include <map_fragment>',`#include <map_fragment>
        #if defined(USE_MAP) && defined(USE_COLOR)
          vec3 camoSample=${camoSample};
          vec3 pigment=${surface?'diffuseColor.rgb':'diffuse'};
          ${surface?'diffuseColor.rgb=pigment*mix(vec3(1.0),camoSample,vTankPaint);':''}
          if(desertCamo){
            float shade=smoothstep(.34,.60,camoSample.r);
            vec3 camo=mix(desertBrown,desertSand,shade)*clamp(vColor.r/.23,.72,1.16);
            diffuseColor.rgb=mix(diffuseColor.rgb,pigment*camo,${paint});
          }
        #endif`);
  };
  material.customProgramCacheKey=()=>surface?'s09-tank-remaster-pbr':'s09-tank-tracks-camo-v1';
  return material;
}

export function createTankRig(materialFactory=null,prepare=null){
  const travel={value:new THREE.Vector2()},group=new THREE.Group();
  const desertCamo={value:false},material=tankMaterial(materialFactory,travel,desertCamo);
  const levels=[0,1,2].map(level=>buildLevel(level,material));for(const l of levels)group.add(l.group);
  const body=new THREE.Group();group.add(body); // Shared seated-actor parent, independent of LOD swaps.
  const shadowMaterial=new THREE.MeshLambertMaterial({colorWrite:false,depthWrite:false}),shadow=new THREE.Mesh(mergeGeometries([levels[1].hull.geometry,levels[1].tracks.geometry],false),shadowMaterial);shadow.castShadow=true;shadow.visible=false;body.add(shadow);
  return {tank:true,group,body,shadow,levels,level:0,material,travel,desertCamo,materialFactory,prepare,materialsToDispose:new Set([material,shadowMaterial]),riders:[],initialized:false};
}
export function updateTankRig(rig,v,p,dt,blend,view,low,terrain){
  position.set(v.x,v.y??0,v.z);
  const group=rig.group,reset=!rig.initialized||group.position.distanceToSquared(position)>64,t=reset?1:blend;
  group.scale.set(v.modelScale?.x??1,v.modelScale?.y??1,v.modelScale?.z??1);
  group.position.lerp(position,t);group.rotation.y+=Math.atan2(Math.sin(v.yaw-group.rotation.y),Math.cos(v.yaw-group.rotation.y))*t;rig.initialized=true;
  const distance=p?Math.hypot(v.x-p.x,v.z-p.z):0,near=low?32:40,far=low?85:100;
  if(rig.level===0&&distance>near*1.06)rig.level=1;else if(rig.level===1&&distance<near*.94)rig.level=0;
  if(rig.level===1&&distance>far*1.06)rig.level=2;else if(rig.level===2&&distance<far*.94)rig.level=1;
  if(p?.vehicleId===v.id)rig.level=0;
  const tilt=reset?1:1-Math.exp(-dt*14);rig.body.rotation.x+=((v.bodyPitch??0)-rig.body.rotation.x)*tilt;rig.body.rotation.z+=((v.bodyRoll??0)-rig.body.rotation.z)*tilt;
  const wantDetail=view.highVehicleDetail&&rig.level===0;
  if(wantDetail&&!rig.detail){
    if(detailAssets){
      const desertCamo={value:false};
      const material=tankMaterial(rig.materialFactory,rig.travel,desertCamo,detailAssets);
      const level=buildLevel('HD',material,detailAssets.parts);
      rig.detail={level,material,desertCamo};
      if(rig.prepare)level.group.traverse(rig.prepare);
      group.add(level.group);
      rig.materialsToDispose.add(material);
    }else if(!detailPromise)void loadTankDetail();
  }
  const showDetail=wantDetail&&Boolean(rig.detail);
  rig.shadow.visible=!showDetail&&rig.level===0&&distance<48;
  rig.travel.value.x+=(v.speed+(v.steer??0)*1.8)*dt*.35;rig.travel.value.y+=(v.speed-(v.steer??0)*1.8)*dt*.35;
  const pose=rig.aimPose??={};pose.yaw=group.rotation.y;pose.modelScale=v.modelScale;pose.bodyPitch=rig.body.rotation.x;pose.bodyRoll=rig.body.rotation.z;
  const direction=vehicleAimDirection(pose,v.aimYaw??v.yaw,v.aimPitch??0,modelDirection),delta=Math.atan2(-direction.x,-direction.z),pitch=Math.atan2(direction.y,Math.hypot(direction.x,direction.z));
  if(reset){rig.cannonSeq=v.cannonSeq;rig.recoil=0;}
  if(rig.cannonSeq!==undefined&&rig.cannonSeq!==v.cannonSeq)rig.recoil=.4;
  rig.wreckAge=v.hp<=0?(rig.wreckAge??0)+dt:0;
  for(let index=0;index<rig.levels.length+(rig.detail?1:0);index++){
    const detailed=index===rig.levels.length;
    const l=detailed?rig.detail.level:rig.levels[index];
    l.group.visible=detailed?showDetail:index===rig.level&&!showDetail;
    if(!l.group.visible)continue;
    l.body.rotation.copy(rig.body.rotation);
    l.turret.rotation.y=delta;l.gun.rotation.x=pitch;
    l.turret.position.set(v.hp<=0?Math.min(3.2,rig.wreckAge*3.2):0,v.hp<=0?Math.max(.15,TANK_TURRET_BASE_Y+rig.wreckAge*8-rig.wreckAge**2*10):TANK_TURRET_BASE_Y,-.4+(v.hp<=0?Math.min(2,rig.wreckAge*2):0));l.turret.rotation.z=v.hp<=0?Math.min(1.1,rig.wreckAge):0;
    l.gun.position.z=-.9+(rig.recoil??0);l.hatch.visible=!(p?.vehicleSeat===0&&p.vehicleId===v.id&&!view.vehicleThirdPerson);
    l.updateBarrel?.();
    l.updateShoes?.(rig.travel.value.x,rig.travel.value.y);
    if(!detailed)l.hull.castShadow=l.turretMesh.castShadow=index===1&&distance<48;
    const wheelRotation=detailed?-1/(.35*.34):5;
    const half=l.wheels.count/2;
    for(let i=0;i<l.wheels.count;i++){
      const left=i<half;
      quaternion.setFromAxisAngle(wheelAxis,(left?rig.travel.value.x:rig.travel.value.y)*wheelRotation);
      matrix.compose(position.set(left?-1.67:1.67,.414,-2.65+i%half*5.3/(half-1)),quaternion,scale.set(1,1,1));
      l.wheels.setMatrixAt(i,matrix);
    }
    l.wheels.instanceMatrix.needsUpdate=true;
  }
  rig.recoil=Math.max(0,(rig.recoil??0)-dt*.8);rig.cannonSeq=v.cannonSeq;
  // Vertex colors and the atlas already darken the hull. Multiplying by
  // 0x383c38 (sRGB -> ~0.04 linear) crushed all wreck surface detail.
  // Deep charcoal soot, retaining atlas highlights and surface detail.
  const applyFinish=({material,desertCamo})=>{
    desertCamo.value=v.camo==='desert';
    if(desertCamo.node)desertCamo.node.value=desertCamo.value?1:0;
    if(v.hp<=0)material.color.setRGB(.23,.205,.18);else material.color.setRGB(1,1,1);
  };
  applyFinish(rig);
  if(rig.detail)applyFinish(rig.detail);
  if(reset)group.updateMatrixWorld(true);
}
export function tankModelStats(rig){return rig.levels.map(l=>{let triangles=0,draws=0;l.group.traverse(o=>{if(o.isMesh){triangles+=(o.geometry.index?.count??o.geometry.attributes.position.count)/3*(o.count??1);draws++;}});return{triangles,draws};});}
