import {gzipSync} from 'node:zlib';
import { FPS_HANDS } from '../art-source/generated/fps-hands-data.js';
import { writeFile } from 'node:fs/promises';
const blocks=[],unique=new Map(),manifest={};let offset=0;
for(const [pose,fields] of Object.entries(FPS_HANDS)){
  manifest[pose]={};for(const [name,encoded] of Object.entries(fields)){
    if(!unique.has(encoded)){const data=Buffer.from(encoded,'base64');unique.set(encoded,[offset,data.length]);blocks.push(data);offset+=data.length;const pad=(4-offset%4)%4;if(pad){blocks.push(Buffer.alloc(pad));offset+=pad;}}
    manifest[pose][name]=unique.get(encoded);
  }
}
await writeFile('src/assets/fps-hands.bin.gz',gzipSync(Buffer.concat(blocks),{level:9}));
await writeFile('src/fps-hands-data.js',`// Generated by scripts/pack-fps-hands.mjs; original DJMaesen / CC BY 4.0 attribution is in art-source/djmaesen-arms/README.md.
import {fetchBinary} from './binary-assets.js';
const layout=${JSON.stringify(manifest)};
export const FPS_HANDS={};let pending;
export function loadFPSHands(){
  return pending??=fetchBinary(new URL('./assets/fps-hands.bin.gz',import.meta.url)).then(buffer=>{for(const [pose,fields] of Object.entries(layout)){FPS_HANDS[pose]={};for(const [name,[offset,length]] of Object.entries(fields))FPS_HANDS[pose][name]=new Uint8Array(buffer,offset,length);}}).catch(error=>{pending=null;throw error;});
}
`);
console.log(`${Object.keys(manifest).length} poses, ${unique.size} shared blocks, ${offset} binary bytes`);
